constexpr util::Logger kLog("report-converter");

using Reports = std::vector<Report>;

// Reads the XML file at `path` (Python: ET.parse(path).getroot()); logs the
// problem and returns nullopt if it fails. `tool` names the tool in the
// message.
std::optional<util::XmlDocument> ParseResult(const std::string& path,
                                             std::string_view tool) {
  const Result<std::string> content = util::ReadFile(path);
  if (!content.ok()) {
    kLog.Error("Analyzer result does not exist: " + path);
    return std::nullopt;
  }
  Result<util::XmlDocument> document = util::ParseXml(content.value());
  if (!document.ok()) {
    kLog.Error("Failed to parse the given analyzer result '" + path +
               "'. Please give a valid xml file with messages generated by " +
               std::string(tool) + ".");
    return std::nullopt;
  }
  return std::move(document).value();
}

// Python: element.find(tag).text, an error if there is no such child.
Result<std::string> ChildText(const xmlNode* element, std::string_view tag) {
  const xmlNode* child = util::XmlFindChild(element, tag);
  if (child == nullptr) {
    return Result<std::string>(Error{
        .message = "AttributeError: 'NoneType' object has no attribute "
                   "'text'"});
  }
  return Result<std::string>(util::XmlText(child).value_or(""));
}

// Python: int(text) of an XML attribute.
Result<int> ToInt(const std::optional<std::string>& text) {
  const std::optional<int64_t> number =
      text ? util::ParseInt(*text) : std::nullopt;
  if (!number) {
    return Result<int>(Error{
        .message = text ? "ValueError: invalid literal for int() with base "
                          "10: " + util::Repr(*text)
                        : "TypeError: int() argument must be a string, a "
                          "bytes-like object or a real number, not "
                          "'NoneType'"});
  }
  return Result<int>(static_cast<int>(*number));
}

// Finds the source files of SpotBugs results (Python: the spotbugs
// AnalyzerResult).
class SpotbugsReader {
 public:
  explicit SpotbugsReader(std::vector<std::string> project_paths)
      : project_paths_(std::move(project_paths)) {}

  SpotbugsReader(const SpotbugsReader&) = delete;
  SpotbugsReader& operator=(const SpotbugsReader&) = delete;

  // Python: __parse_bug(); nullopt if its source file is not found.
  Result<std::optional<Report>> ReadBug(const xmlNode* bug) const;

 private:
  // Python: __get_abs_path().
  std::optional<std::string> SourcePath(const xmlNode* source_line) const;
  // Python: __event_from_class() and __event_from_method().
  Result<std::optional<BugPathEvent>> Event(const xmlNode* element) const;

  std::vector<std::string> project_paths_;
};

std::optional<std::string> SpotbugsReader::SourcePath(
    const xmlNode* source_line) const {
  if (source_line == nullptr) return std::nullopt;
  const std::optional<std::string> path =
      util::XmlAttribute(source_line, "sourcepath");
  if (!path) {
    kLog.Warning(
        "No source path attribute found for class: " +
        util::XmlAttribute(source_line, "classname").value_or("None"));
    return std::nullopt;
  }
  if (util::pypath::Exists(*path)) return path;
  for (const std::string& project_path : project_paths_) {
    const std::string full = util::pypath::Join({project_path, *path});
    if (util::pypath::Exists(full)) return full;
  }
  kLog.Warning("No source file found: " + *path);
  return std::nullopt;
}

Result<std::optional<BugPathEvent>> SpotbugsReader::Event(
    const xmlNode* element) const {
  using EventResult = Result<std::optional<BugPathEvent>>;
  const Result<std::string> message = ChildText(element, "Message");
  if (!message.ok()) return EventResult(message.error());
  const xmlNode* source_line = util::XmlFindChild(element, "SourceLine");
  const std::optional<std::string> path = SourcePath(source_line);
  if (!path) return EventResult(std::nullopt);
  const Result<int> line =
      ToInt(util::XmlAttribute(source_line, "start").value_or("0"));
  if (!line.ok()) return EventResult(line.error());
  return EventResult(BugPathEvent{.message = message.value(),
                                  .file = MakeFile(*path),
                                  .line = line.value(),
                                  .column = 0});
}

Result<std::optional<Report>> SpotbugsReader::ReadBug(
    const xmlNode* bug) const {
  using ReportResult = Result<std::optional<Report>>;
  const Result<std::string> message = ChildText(bug, "LongMessage");
  if (!message.ok()) return ReportResult(message.error());
  const xmlNode* source_line = util::XmlFindChild(bug, "SourceLine");
  const std::optional<std::string> path = SourcePath(source_line);
  if (!path) return ReportResult(std::nullopt);
  std::vector<BugPathEvent> events;
  for (const xmlNode* element : util::XmlChildren(bug)) {
    const std::string_view tag = util::XmlTag(element);
    if (tag != "Class" && tag != "Method") continue;
    Result<std::optional<BugPathEvent>> event = Event(element);
    if (!event.ok()) return ReportResult(event.error());
    if (event.value()) events.push_back(*event.value());
  }
  std::optional<std::string> start = util::XmlAttribute(source_line, "start");
  if (!start) {
    // Without a start line, the line of the last event that has one.
    start = "0";
    for (auto event = events.rbegin(); event != events.rend(); ++event) {
      if (event->line > 0) {
        start = std::to_string(event->line);
        break;
      }
    }
  }
  const Result<int> line = ToInt(start);
  if (!line.ok()) return ReportResult(line.error());
  Report report =
      MakeReport(MakeFile(*path), line.value(), 0, message.value(),
                 util::XmlAttribute(bug, "type").value_or(""),
                 std::move(events));
  report.report_hash = util::XmlAttribute(bug, "instanceHash");
  report.bug_path_events.push_back({.message = report.message,
                                    .file = report.file,
                                    .line = report.line,
                                    .column = report.column});
  return ReportResult(std::move(report));
}

