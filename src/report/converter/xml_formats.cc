Result<Reports> GetSpotbugsReports(const std::string& path) {
  Reports reports;
  const std::optional<util::XmlDocument> document =
      ParseResult(path, "SpotBugs");
  if (!document) return Result<Reports>(std::move(reports));
  const xmlNode* root = util::XmlRoot(*document);
  const xmlNode* project = util::XmlFindChild(root, "Project");
  if (project == nullptr) {
    return Result<Reports>(
        Error{.message = "TypeError: 'NoneType' object is not iterable"});
  }
  std::vector<std::string> project_paths;
  for (const xmlNode* element : util::XmlChildren(project)) {
    const std::string_view tag = util::XmlTag(element);
    if (tag != "Jar" && tag != "AuxClasspathEntry" && tag != "SrcDir") {
      continue;
    }
    const std::string file = util::XmlText(element).value_or("");
    if (util::pypath::IsDir(file)) {
      project_paths.push_back(file);
    } else if (util::pypath::IsFile(file)) {
      project_paths.push_back(util::pypath::Dirname(file));
    }
  }
  const SpotbugsReader reader(std::move(project_paths));
  for (const xmlNode* bug : util::XmlChildren(root)) {
    if (util::XmlTag(bug) != "BugInstance") continue;
    Result<std::optional<Report>> report = reader.ReadBug(bug);
    if (!report.ok()) return Result<Reports>(report.error());
    if (report.value()) reports.push_back(*std::move(report).value());
  }
  return Result<Reports>(std::move(reports));
}

Result<Reports> GetRoslynatorReports(const std::string& path) {
  Reports reports;
  const std::optional<util::XmlDocument> document =
      ParseResult(path, "Roslynator");
  if (!document) return Result<Reports>(std::move(reports));
  // Python: root.findall('./CodeAnalysis/Projects/*/Diagnostics/*').
  std::vector<const xmlNode*> diagnostics;
  for (const xmlNode* analysis : util::XmlChildren(util::XmlRoot(*document))) {
    if (util::XmlTag(analysis) != "CodeAnalysis") continue;
    for (const xmlNode* projects : util::XmlChildren(analysis)) {
      if (util::XmlTag(projects) != "Projects") continue;
      for (const xmlNode* project : util::XmlChildren(projects)) {
        for (const xmlNode* list : util::XmlChildren(project)) {
          if (util::XmlTag(list) != "Diagnostics") continue;
          for (const xmlNode* diagnostic : util::XmlChildren(list)) {
            diagnostics.push_back(diagnostic);
          }
        }
      }
    }
  }
  for (const xmlNode* diagnostic : diagnostics) {
    const std::string id = util::XmlAttribute(diagnostic, "Id").value_or("");
    const xmlNode* file_path = util::XmlFindChild(diagnostic, "FilePath");
    if (file_path == nullptr) {
      kLog.Warning("Diagnostic does not belong to a file: " + id);
      continue;
    }
    const std::string source = util::pypath::Join(
        {util::pypath::Dirname(path), util::XmlText(file_path).value_or("")});
    if (!util::pypath::Exists(source)) {
      kLog.Warning("Source file does not exist: " + source);
      continue;
    }
    const Result<std::string> message = ChildText(diagnostic, "Message");
    if (!message.ok()) return Result<Reports>(message.error());
    const xmlNode* location = util::XmlFindChild(diagnostic, "Location");
    if (location == nullptr) {
      return Result<Reports>(Error{
          .message = "AttributeError: 'NoneType' object has no attribute "
                     "'attrib'"});
    }
    const Result<int> line = ToInt(util::XmlAttribute(location, "Line"));
    const Result<int> column =
        ToInt(util::XmlAttribute(location, "Character"));
    if (!line.ok()) return Result<Reports>(line.error());
    if (!column.ok()) return Result<Reports>(column.error());
    reports.push_back(MakeReport(MakeFile(source), line.value(),
                                 column.value(), message.value(), id));
  }
  return Result<Reports>(std::move(reports));
}

