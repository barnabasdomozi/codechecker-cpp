using Reports = std::vector<Report>;

// The ways a JSON input file can fail to load.
enum class LoadFailure { kNone, kMissing, kInvalid };

// Reads the JSON file at `path`, decoded with undecodable bytes dropped.
// `failure` says why it returned nullopt.
std::optional<util::JsonDocument> LoadJson(const std::string& path,
                                           LoadFailure* failure) {
  *failure = LoadFailure::kNone;
  if (!util::pypath::Exists(path)) {
    *failure = LoadFailure::kMissing;
    return std::nullopt;
  }
  const Result<std::string> content = util::ReadFile(path);
  if (!content.ok()) {
    *failure = LoadFailure::kInvalid;
    return std::nullopt;
  }
  Result<util::JsonDocument> document =
      util::ParseJson(util::DecodeUtf8Ignore(content.value()));
  if (!document.ok()) {
    *failure = LoadFailure::kInvalid;
    return std::nullopt;
  }
  return std::move(document).value();
}

// Reads the JSON output of `tool` like the pylint, ruff, eslint and tslint
// converters do, and logs their errors.
std::optional<util::JsonDocument> LoadToolJson(const std::string& path,
                                               std::string_view tool) {
  LoadFailure failure = LoadFailure::kNone;
  std::optional<util::JsonDocument> document = LoadJson(path, &failure);
  if (failure == LoadFailure::kMissing) {
    kLog.Error("Report file does not exist: " + path);
  } else if (failure == LoadFailure::kInvalid) {
    kLog.Error("Failed to parse the given analyzer result '" + path +
               "'. Please give a valid json file generated by " +
               std::string(tool) + ".");
  }
  return document;
}

// Returns the items of the JSON array `value` (Python: `for item in value`),
// or Python's error for values that cannot be iterated like a list.
Result<std::vector<yyjson_val*>> Items(yyjson_val* value) {
  using Values = std::vector<yyjson_val*>;
  if (!yyjson_is_arr(value)) {
    return Result<Values>(Error{
        .message = std::string("TypeError: '") + yyjson_get_type_desc(value) +
                   "' object is not iterable"});
  }
  Values items;
  yyjson_arr_iter iter = yyjson_arr_iter_with(value);
  while (yyjson_val* item = yyjson_arr_iter_next(&iter)) items.push_back(item);
  return Result<Values>(std::move(items));
}

// Python: value.get(key, []) for a list member.
std::vector<yyjson_val*> ItemsOrEmpty(yyjson_val* value,
                                      std::string_view key) {
  Result<std::vector<yyjson_val*>> items = Items(util::JsonGet(value, key));
  return items.ok() ? std::move(items).value() : std::vector<yyjson_val*>();
}

// Python: str(value[key]); a missing key is an error.
Result<std::string> GetString(yyjson_val* value, std::string_view key) {
  const Result<yyjson_val*> member = util::JsonSubscript(value, key);
  if (!member.ok()) return Result<std::string>(member.error());
  return Result<std::string>(util::JsonToStr(member.value()));
}

// Python: int(value[key]).
Result<int> GetInt(yyjson_val* value, std::string_view key) {
  const Result<int64_t> number = util::JsonSubscriptInt(value, key);
  if (!number.ok()) return Result<int>(number.error());
  return Result<int>(static_cast<int>(number.value()));
}

// The checker name of a finding: a null name means none, so the type's name
// is used.
std::string CheckerName(yyjson_val* value) {
  return value == nullptr || yyjson_is_null(value) ? ""
                                                   : util::JsonToStr(value);
}

// Returns the error of `result`, or null if it succeeded.
template <typename T>
const Error* ErrorOf(const Result<T>& result) {
  return result.ok() ? nullptr : &result.error();
}

// Returns the first of `errors` that is not null, if any.
std::optional<Error> FirstError(std::initializer_list<const Error*> errors) {
  for (const Error* error : errors) {
    if (error != nullptr) return *error;
  }
  return std::nullopt;
}

