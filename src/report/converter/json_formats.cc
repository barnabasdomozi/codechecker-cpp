Result<Reports> GetPylintReports(const std::string& path) {
  Reports reports;
  const std::optional<util::JsonDocument> document =
      LoadToolJson(path, "Pylint");
  if (!document) return Result<Reports>(std::move(reports));
  Result<std::vector<yyjson_val*>> bugs =
      Items(yyjson_doc_get_root(document->get()));
  if (!bugs.ok()) return Result<Reports>(bugs.error());
  for (yyjson_val* bug : bugs.value()) {
    const std::string source = util::pypath::Join(
        {util::pypath::Dirname(path),
         util::JsonToStr(util::JsonGet(bug, "path"))});
    if (!util::pypath::Exists(source)) {
      kLog.Warning("Source file does not exists: " + source);
      continue;
    }
    const Result<int> line = GetInt(bug, "line");
    const Result<int> column = GetInt(bug, "column");
    const Result<std::string> message = GetString(bug, "message");
    const Result<std::string> symbol = GetString(bug, "symbol");
    if (std::optional<Error> error = FirstError(
            {ErrorOf(line), ErrorOf(column), ErrorOf(message),
             ErrorOf(symbol)})) {
      return Result<Reports>(*error);
    }
    reports.push_back(MakeReport(MakeFile(util::pypath::Abspath(source)),
                                 line.value(), column.value(), message.value(),
                                 symbol.value()));
  }
  return Result<Reports>(std::move(reports));
}

Result<Reports> GetRuffReports(const std::string& path) {
  Reports reports;
  const std::optional<util::JsonDocument> document = LoadToolJson(path, "ruff");
  if (!document) return Result<Reports>(std::move(reports));
  Result<std::vector<yyjson_val*>> bugs =
      Items(yyjson_doc_get_root(document->get()));
  if (!bugs.ok()) return Result<Reports>(bugs.error());
  for (yyjson_val* bug : bugs.value()) {
    std::string source = util::JsonToStr(util::JsonGet(bug, "filename"));
    // Ruff writes absolute paths; relative ones are relative to the input.
    const std::string relative =
        util::pypath::Join({util::pypath::Dirname(path), source});
    if (util::pypath::Exists(relative)) source = relative;
    if (!util::pypath::Exists(source)) {
      kLog.Warning("Source file does not exists: " + source);
      continue;
    }
    const Result<yyjson_val*> location = util::JsonSubscript(bug, "location");
    if (!location.ok()) return Result<Reports>(location.error());
    const Result<int> row = GetInt(location.value(), "row");
    const Result<int> column = GetInt(location.value(), "column");
    const Result<std::string> message = GetString(bug, "message");
    const Result<std::string> code = GetString(bug, "code");
    if (std::optional<Error> error = FirstError(
            {ErrorOf(row), ErrorOf(column), ErrorOf(message), ErrorOf(code)})) {
      return Result<Reports>(*error);
    }
    reports.push_back(MakeReport(MakeFile(util::pypath::Abspath(source)),
                                 row.value(), column.value(), message.value(),
                                 CheckerName(util::JsonGet(bug, "code"))));
  }
  return Result<Reports>(std::move(reports));
}

Result<Reports> GetEslintReports(const std::string& path) {
  Reports reports;
  const std::optional<util::JsonDocument> document =
      LoadToolJson(path, "ESLint");
  if (!document) return Result<Reports>(std::move(reports));
  Result<std::vector<yyjson_val*>> diagnostics =
      Items(yyjson_doc_get_root(document->get()));
  if (!diagnostics.ok()) return Result<Reports>(diagnostics.error());
  // As in the Python version, each source path is joined to the folder of
  // the previous one (for absolute paths, as ESLint writes, it is the same).
  std::string source = path;
  for (yyjson_val* diagnostic : diagnostics.value()) {
    source = util::pypath::Join(
        {util::pypath::Dirname(source),
         util::JsonToStr(util::JsonGet(diagnostic, "filePath"))});
    if (!util::pypath::Exists(source)) {
      kLog.Warning("Source file does not exists: " + source);
      continue;
    }
    Result<std::vector<yyjson_val*>> messages =
        Items(util::JsonGet(diagnostic, "messages"));
    if (!messages.ok()) continue;
    for (yyjson_val* bug : messages.value()) {
      const Result<int> line = GetInt(bug, "line");
      const Result<yyjson_val*> column = util::JsonSubscript(bug, "column");
      const Result<std::string> message = GetString(bug, "message");
      const Result<yyjson_val*> rule = util::JsonSubscript(bug, "ruleId");
      if (std::optional<Error> error = FirstError(
              {ErrorOf(line), ErrorOf(column), ErrorOf(message),
               ErrorOf(rule)})) {
        return Result<Reports>(*error);
      }
      reports.push_back(MakeReport(
          MakeFile(util::pypath::Abspath(source)), line.value(),
          static_cast<int>(util::JsonToInt(column.value()).value_or(0)),
          message.value(), CheckerName(rule.value())));
    }
  }
  return Result<Reports>(std::move(reports));
}

Result<Reports> GetTslintReports(const std::string& path) {
  Reports reports;
  const std::optional<util::JsonDocument> document =
      LoadToolJson(path, "TSLint");
  if (!document) return Result<Reports>(std::move(reports));
  Result<std::vector<yyjson_val*>> bugs =
      Items(yyjson_doc_get_root(document->get()));
  if (!bugs.ok()) return Result<Reports>(bugs.error());
  for (yyjson_val* bug : bugs.value()) {
    const std::string source = util::pypath::Join(
        {util::pypath::Dirname(path),
         util::JsonToStr(util::JsonGet(bug, "name"))});
    if (!util::pypath::Exists(source)) {
      kLog.Warning("Source file does not exists: " + source);
      continue;
    }
    const Result<yyjson_val*> start = util::JsonSubscript(bug, "startPosition");
    if (!start.ok()) return Result<Reports>(start.error());
    const Result<int> line = GetInt(start.value(), "line");
    const Result<int> character = GetInt(start.value(), "character");
    const Result<std::string> failure = GetString(bug, "failure");
    const Result<yyjson_val*> rule = util::JsonSubscript(bug, "ruleName");
    if (std::optional<Error> error =
            FirstError({ErrorOf(line), ErrorOf(character), ErrorOf(failure),
                        ErrorOf(rule)})) {
      return Result<Reports>(*error);
    }
    reports.push_back(MakeReport(MakeFile(util::pypath::Abspath(source)),
                                 line.value() + 1, character.value() + 1,
                                 failure.value(), CheckerName(rule.value())));
  }
  return Result<Reports>(std::move(reports));
}

Result<Reports> GetPvsStudioReports(const std::string& path) {
  constexpr std::string_view kSeverities[] = {"UNSPECIFIED", "HIGH", "MEDIUM",
                                              "LOW"};
  Reports reports;
  LoadFailure failure = LoadFailure::kNone;
  const std::optional<util::JsonDocument> document = LoadJson(path, &failure);
  if (failure == LoadFailure::kMissing) {
    kLog.Info("Report file does not exist: " + path);
    return Result<Reports>(std::move(reports));
  }
  if (failure == LoadFailure::kInvalid) {
    kLog.Warning("Failed to parse the given analyzer result '" + path +
                 "'. Please give a valid json file generated by PVS-Studio.");
    return Result<Reports>(std::move(reports));
  }
  const Result<yyjson_val*> warnings =
      util::JsonSubscript(yyjson_doc_get_root(document->get()), "warnings");
  if (!warnings.ok()) return Result<Reports>(warnings.error());
  Result<std::vector<yyjson_val*>> bugs = Items(warnings.value());
  if (!bugs.ok()) return Result<Reports>(bugs.error());
  for (yyjson_val* bug : bugs.value()) {
    const Result<yyjson_val*> positions = util::JsonSubscript(bug, "positions");
    if (!positions.ok()) return Result<Reports>(positions.error());
    Result<std::vector<yyjson_val*>> items = Items(positions.value());
    if (!items.ok()) return Result<Reports>(items.error());
    for (yyjson_val* position : items.value()) {
      const Result<std::string> source = GetString(position, "file");
      if (!source.ok()) return Result<Reports>(source.error());
      if (!util::pypath::Exists(source.value())) {
        kLog.Warning("Source file does not exist: " + source.value());
        continue;
      }
      const Result<int> line = GetInt(position, "line");
      const Result<std::string> message = GetString(bug, "message");
      const Result<std::string> code = GetString(bug, "code");
      if (std::optional<Error> error = FirstError(
              {ErrorOf(line), ErrorOf(message), ErrorOf(code)})) {
        return Result<Reports>(*error);
      }
      // Python indexes its list of severities, negative indexes included.
      const std::optional<int64_t> level =
          util::JsonToInt(util::JsonGet(bug, "level"));
      if (!level || *level < -4 || *level > 3) {
        return Result<Reports>(
            Error{.message = "IndexError: list index out of range"});
      }
      Report report = MakeReport(
          MakeFile(util::pypath::Abspath(source.value())), line.value(),
          static_cast<int>(
              util::JsonToInt(util::JsonGet(position, "column")).value_or(0)),
          message.value(), code.value());
      report.severity = std::string(kSeverities[(*level + 4) % 4]);
      reports.push_back(std::move(report));
    }
  }
  return Result<Reports>(std::move(reports));
}

Result<Reports> GetJscpdReports(const std::string& path) {
  Reports reports;
  LoadFailure failure = LoadFailure::kNone;
  const std::optional<util::JsonDocument> document = LoadJson(path, &failure);
  if (!document) {
    kLog.Error("Failed to parse the given analyzer result '" + path +
               "'. Please give a valid json file generated by jscpd.");
    return Result<Reports>(std::move(reports));
  }
  yyjson_val* root = yyjson_doc_get_root(document->get());
  if (yyjson_is_null(root) ||
      (yyjson_is_obj(root) && yyjson_obj_size(root) == 0) ||
      (yyjson_is_arr(root) && yyjson_arr_size(root) == 0)) {
    return Result<Reports>(std::move(reports));
  }
  const Result<yyjson_val*> duplicates =
      util::JsonSubscript(root, "duplicates");
  if (!duplicates.ok()) return Result<Reports>(duplicates.error());
  Result<std::vector<yyjson_val*>> items = Items(duplicates.value());
  if (!items.ok()) return Result<Reports>(items.error());
  for (yyjson_val* duplicate : items.value()) {
    const Result<yyjson_val*> first =
        util::JsonSubscript(duplicate, "firstFile");
    const Result<yyjson_val*> second =
        util::JsonSubscript(duplicate, "secondFile");
    if (std::optional<Error> error = FirstError(
            {ErrorOf(first), ErrorOf(second)})) {
      return Result<Reports>(*error);
    }
    const Result<std::string> first_name = GetString(first.value(), "name");
    const Result<std::string> second_name = GetString(second.value(), "name");
    const Result<yyjson_val*> first_start =
        util::JsonSubscript(first.value(), "startLoc");
    const Result<yyjson_val*> second_start =
        util::JsonSubscript(second.value(), "startLoc");
    const Result<std::string> lines = GetString(duplicate, "lines");
    if (std::optional<Error> error = FirstError(
            {ErrorOf(first_name), ErrorOf(second_name), ErrorOf(first_start),
             ErrorOf(second_start), ErrorOf(lines)})) {
      return Result<Reports>(*error);
    }
    for (const std::string& name : {first_name.value(), second_name.value()}) {
      if (!util::pypath::Exists(name)) {
        kLog.Warning("Source file does not exist or cannot be found: " +
                     name +
                     ". If needed, use the -a flag when generating the JSCPD "
                     "report to include the absolute path.");
      }
    }
    const Result<int> first_line = GetInt(first_start.value(), "line");
    const Result<int> first_column = GetInt(first_start.value(), "column");
    const Result<int> second_line = GetInt(second_start.value(), "line");
    const Result<int> second_column = GetInt(second_start.value(), "column");
    if (std::optional<Error> error = FirstError(
            {ErrorOf(first_line), ErrorOf(first_column), ErrorOf(second_line),
             ErrorOf(second_column)})) {
      return Result<Reports>(*error);
    }
    Report report = MakeReport(
        MakeFile(first_name.value()), first_line.value(), first_column.value(),
        "Duplicated code of " + lines.value() + " lines. Duplicates " +
            second_name.value() + ", starting line " +
            std::to_string(second_line.value()),
        "jscpd", std::vector<BugPathEvent>());
    report.category = "jscpd";
    report.notes.push_back(
        {.message = "Duplicated code of " + lines.value() +
                    " lines. Duplicates " + first_name.value() +
                    ", starting line " + std::to_string(first_line.value()),
         .file = MakeFile(second_name.value()),
         .line = second_line.value(),
         .column = second_column.value()});
    reports.push_back(std::move(report));
  }
  return Result<Reports>(std::move(reports));
}

Result<Reports> GetPmdReports(const std::string& path) {
  const Result<std::string> content = util::ReadFile(path);
  if (!content.ok()) return Result<Reports>(content.error());
  if (util::DecodeUtf8Ignore(content.value()).size() !=
      content.value().size()) {
    return Result<Reports>(Error{
        .message = "UnicodeDecodeError: 'utf-8' codec can't decode the file " +
                   path});
  }
  const Result<util::JsonDocument> document = util::ParseJson(content.value());
  if (!document.ok()) {
    return Result<Reports>(Error{.message = "json.decoder.JSONDecodeError: " +
                                            document.error().message});
  }
  Reports reports;
  yyjson_val* root = yyjson_doc_get_root(document.value().get());
  if (!yyjson_is_obj(root)) {
    return Result<Reports>(Error{
        .message = std::string("AttributeError: '") +
                   yyjson_get_type_desc(root) +
                   "' object has no attribute 'get'"});
  }
  for (yyjson_val* entry : ItemsOrEmpty(root, "files")) {
    const Result<std::string> filename = GetString(entry, "filename");
    if (!filename.ok()) return Result<Reports>(filename.error());
    const File file = MakeFile(util::pypath::Abspath(filename.value()));
    for (yyjson_val* violation : ItemsOrEmpty(entry, "violations")) {
      yyjson_val* line = util::JsonGet(violation, "beginline");
      yyjson_val* column = util::JsonGet(violation, "begincolumn");
      yyjson_val* message = util::JsonGet(violation, "description");
      yyjson_val* rule = util::JsonGet(violation, "rule");
      yyjson_val* ruleset = util::JsonGet(violation, "ruleset");
      Report report = MakeReport(
          file,
          line != nullptr ? static_cast<int>(util::JsonToInt(line).value_or(1))
                          : 1,
          column != nullptr
              ? static_cast<int>(util::JsonToInt(column).value_or(1))
              : 1,
          message != nullptr ? util::JsonToStr(message) : "",
          rule != nullptr ? util::JsonToStr(rule) : "unknown");
      report.category =
          ruleset != nullptr ? util::JsonToStr(ruleset) : "unknown";
      reports.push_back(std::move(report));
    }
  }
  return Result<Reports>(std::move(reports));
}

Result<Reports> GetInferReports(const std::string& path) {
  Reports reports;
  std::string report_file = path;
  std::string parent = util::pypath::Dirname(util::pypath::Dirname(path));
  if (util::pypath::IsDir(path)) {
    report_file = util::pypath::Join({path, "report.json"});
    parent = util::pypath::Dirname(path);
  }
  if (!util::pypath::Exists(report_file)) {
    kLog.Error("Report file does not exist: " + report_file);
    return Result<Reports>(std::move(reports));
  }
  const Result<std::string> content = util::ReadFile(report_file);
  if (!content.ok()) {
    kLog.Error("Failed to parse the given analyzer result '" + path +
               "'. Please give an infer output directory which contains a "
               "valid 'report.json' file.");
    return Result<Reports>(std::move(reports));
  }
  const Result<util::JsonDocument> document =
      util::ParseJson(util::DecodeUtf8Ignore(content.value()));
  if (!document.ok()) {
    return Result<Reports>(Error{.message = "json.decoder.JSONDecodeError: " +
                                            document.error().message});
  }
  // Python: __get_abs_path(); nullopt if the file is not found.
  const auto find_source =
      [&parent](const std::string& source) -> std::optional<std::string> {
    if (util::pypath::Exists(source)) return util::pypath::Abspath(source);
    const std::string full = util::pypath::Join({parent, source});
    if (util::pypath::Exists(full)) return full;
    const std::string absolute = util::pypath::Join({"/", source});
    if (util::pypath::Exists(absolute)) return absolute;
    kLog.Warning("No source file found: " + source);
    return std::nullopt;
  };
  Result<std::vector<yyjson_val*>> bugs =
      Items(yyjson_doc_get_root(document.value().get()));
  if (!bugs.ok()) return Result<Reports>(bugs.error());
  for (yyjson_val* bug : bugs.value()) {
    const Result<std::string> hash = GetString(bug, "hash");
    const Result<std::string> checker = GetString(bug, "bug_type");
    const Result<std::string> message = GetString(bug, "qualifier");
    const Result<int> line = GetInt(bug, "line");
    const Result<int> column = GetInt(bug, "column");
    const Result<std::string> file = GetString(bug, "file");
    if (std::optional<Error> error =
            FirstError({ErrorOf(hash), ErrorOf(checker), ErrorOf(message),
                        ErrorOf(line), ErrorOf(column), ErrorOf(file)})) {
      return Result<Reports>(*error);
    }
    const std::optional<std::string> source = find_source(file.value());
    if (!source) continue;
    Report report = MakeReport(MakeFile(util::pypath::Abspath(*source)),
                               line.value(), std::max(column.value(), 0),
                               message.value(), checker.value(),
                               std::vector<BugPathEvent>());
    report.report_hash = hash.value();
    const Result<yyjson_val*> trace = util::JsonSubscript(bug, "bug_trace");
    if (!trace.ok()) return Result<Reports>(trace.error());
    Result<std::vector<yyjson_val*>> steps = Items(trace.value());
    if (!steps.ok()) return Result<Reports>(steps.error());
    for (yyjson_val* step : steps.value()) {
      const Result<std::string> filename = GetString(step, "filename");
      if (!filename.ok()) return Result<Reports>(filename.error());
      const std::optional<std::string> step_source =
          find_source(filename.value());
      if (!step_source) continue;
      const Result<std::string> description = GetString(step, "description");
      const Result<int> step_line = GetInt(step, "line_number");
      const Result<int> step_column = GetInt(step, "column_number");
      if (std::optional<Error> error = FirstError(
              {ErrorOf(description), ErrorOf(step_line),
               ErrorOf(step_column)})) {
        return Result<Reports>(*error);
      }
      report.bug_path_events.push_back(
          {.message = description.value(),
           .file = MakeFile(*step_source),
           .line = step_line.value(),
           .column = std::max(step_column.value(), 0)});
    }
    report.bug_path_events.push_back({.message = report.message,
                                      .file = report.file,
                                      .line = report.line,
                                      .column = report.column});
    reports.push_back(std::move(report));
  }
  return Result<Reports>(std::move(reports));
}

