void CreateMakefile(const std::vector<std::string>& analyzers,
                    const std::string& output_path,
                    const std::map<std::string, AnalyzerConfig>& configs,
                    bool pre_analysis,
                    const std::optional<StatisticsData>& statistics,
                    const std::optional<CtuData>& ctu_data,
                    const std::vector<BuildAction>& actions) {
  const std::string makefile = util::pypath::Join({output_path, "Makefile"});
  kLog.Info("Creating Makefile from the analyzer commands: '" + makefile +
            "'...");
  const Result<AnalyzerContext*> context = GetContext();
  std::string text = std::format(
      "#\n# Autogenerated by CodeChecker v{}.\n#\n# DO NOT EDIT UNLESS YOU ARE "
      "SURE THAT YOU KNOW WHAT YOU ARE DOING.\n#\n\n",
      context.ok() ? context.value()->version() : "");
  if (const std::optional<std::string> data_dir =
          platform::GetEnv("CC_DATA_FILES_DIR");
      data_dir && !data_dir->empty()) {
    text += std::format(
        "export PATH := {}:{}:${{PATH}}\n",
        platform::GetEnv("CC_BIN_DIR").value_or(""),
        util::pypath::Join({*data_dir, "python3", "bin"}));
  }
  for (const char* name : {"LD_LIBRARY_PATH", "PYTHONPATH", "PYTHONHOME"}) {
    if (const std::optional<std::string> value = platform::GetEnv(name);
        value && !value->empty()) {
      text += std::format("export {} := {}\n", name, *value);
    }
  }
  text += "\n# Default target to run all analysis.\ndefault: all\n\n";
  for (const std::string& analyzer : analyzers) {
    text +=
        std::format("# Target to run only '{0}' analysis.\nall: all_{0}\n\n",
                    AnalyzerTag(analyzer));
  }
  const std::string pre_all_target = "pre_all_" + AnalyzerTag("clangsa");
  const auto clangsa_config = configs.find("clangsa");
  for (const BuildAction& action : actions) {
    const std::string target = TargetName(action);
    std::string post_pre_all_target;
    if (pre_analysis && action.analyzer_type == "clangsa") {
      std::vector<std::string> commands;
      if (ctu_data) {
        for (std::string& command : CtuPreAnalysisCommands(
                 action, clangsa_config->second, *ctu_data)) {
          commands.push_back(std::move(command));
        }
      }
      if (statistics) {
        for (std::string& command : StatsPreAnalysisCommands(
                 action, clangsa_config->second, *statistics)) {
          commands.push_back(std::move(command));
        }
      }
      std::string recipe;
      for (size_t i = 0; i < commands.size(); ++i) {
        if (i > 0) recipe += "\n";
        recipe += "\t@" + commands[i];
      }
      text += std::format("pre_{0}:\n\t@echo \"{1} Pre-analysis of {2}.\"\n"
                          "{3}\n{4}: pre_{0}\n\n",
                          target, kLogInfo, action.source, recipe,
                          pre_all_target);
      post_pre_all_target = "post_" + pre_all_target;
    }
    // Python: __write_analysis_targets().
    const AnalyzerConfig& config = configs.at(action.analyzer_type);
    Result<AnalyzerRun> prepared =
        PrepareRun(action, config, output_path, statistics,
                   /*disable_ctu=*/false);
    if (!prepared.ok()) continue;
    AnalyzerRun run = std::move(prepared).value();
    // Python computes the action hash only when the result file name is
    // first used, which the cppcheck and infer commands do not do: they
    // write into <output>/cppcheck and <output>/infer here.
    run.action_hash.clear();
    if (statistics && !post_pre_all_target.empty()) {
      run.checker_configs.push_back(
          StatisticsAnalyzeConfig(statistics->stats_out_dir));
    }
    std::vector<std::string> quoted;
    for (const std::string& arg :
         FindAnalyzer(action.analyzer_type)->BuildCommand(&run)) {
      quoted.push_back(util::ShlexQuote(arg));
    }
    const std::string analyzer_command = util::Join(quoted, " ");
    std::string command;
    if (action.analyzer_type == "clang-tidy") {
      const std::string output_file = run.result_file + ".output";
      command = std::format(
          "@{} > {}\n\t@report-converter -t clang-tidy -o {} --filename "
          "{{source_file}}_{{analyzer}}_{} {} 1>/dev/null\n\t@rm -rf {}\n",
          analyzer_command, output_file, output_path, target, output_file,
          output_file);
    } else {
      command = "@" + analyzer_command + " 1>/dev/null";
    }
    text += std::format("{0}: {1}\n\t@echo \"{2} {3} analyze {4}.\"\n\t{5}\n"
                        "all_{6}: {0}\n\n",
                        target, post_pre_all_target, kLogInfo,
                        action.analyzer_type, action.source, command,
                        AnalyzerTag(action.analyzer_type));
  }
  if (pre_analysis) {
    std::vector<std::string> commands;
    if (ctu_data) {
      commands.push_back(std::format(
          "find {} -maxdepth 1 -mindepth 1 -type d -exec "
          "merge-clang-extdef-mappings -i {{}}/{} -o {{}}/externalDefMap.txt "
          "\\;",
          ctu_data->ctu_dir, kCtuTempFnMapFolder));
    }
    if (statistics) {
      commands.push_back("post-process-stats -i " + statistics->stat_tmp_dir +
                         " " + statistics->stats_out_dir);
    }
    std::string recipe;
    for (size_t i = 0; i < commands.size(); ++i) {
      if (i > 0) recipe += "\n";
      recipe += "\t@" + commands[i];
    }
    text += std::format("post_{0}: {0}\n{1}\n\n", pre_all_target, recipe);
  }
  (void)util::WriteFile(makefile, text);
  kLog.Info("Done.");
}

