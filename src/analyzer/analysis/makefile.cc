constexpr util::Logger kLog("analyzer");
constexpr std::string_view kLogInfo = "[`date +'%Y-%m-%d %H:%M:%S'`] -";

// Returns the analyzer name without "-" (Python: __format_analyzer_type()).
std::string AnalyzerTag(std::string name) {
  std::erase(name, '-');
  return name;
}

// Python: __get_target_name().
std::string TargetName(const BuildAction& action) {
  return util::Md5Hex(AnalyzerTag(action.analyzer_type) + "_" + action.source +
                      "_" + action.original_command);
}

// Python: __get_ctu_pre_analysis_cmds().
std::vector<std::string> CtuPreAnalysisCommands(const BuildAction& action,
                                                const AnalyzerConfig& config,
                                                const CtuData& ctu_data) {
  std::vector<std::string> commands;
  const std::string triple_arch = TripleArch(action, action.source, config);
  std::string ast_dir;
  const std::vector<std::string> ast =
      AstCommand(action, config, triple_arch, action.source, &ast_dir);
  commands.push_back("mkdir -p " + ast_dir);
  commands.push_back(util::Join(ast, " "));
  const std::vector<std::string> mapping = ExtdefMappingCommand(
      action, config, action.source,
      ctu_data.mapping ? ctu_data.mapping->tool : "None");
  const std::string fnmap_dir = util::pypath::Join(
      {ctu_data.ctu_dir, triple_arch, kCtuTempFnMapFolder});
  commands.push_back("mkdir -p " + fnmap_dir);
  const std::string map_file = util::pypath::Join({fnmap_dir, util::Uuid4()});
  commands.push_back(util::Join(mapping, " ") + " > " + map_file +
                     " 2>/dev/null");
  // The map gets relative AST paths; sed -i would differ on macOS.
  commands.push_back("sed -E \"s|/(.*)|ast/\\1.ast|\" " + map_file + " > " +
                     map_file + "_tmp");
  commands.push_back("mv -f " + map_file + "_tmp " + map_file);
  return commands;
}

// Python: __get_stats_pre_analysis_cmds().
std::vector<std::string> StatsPreAnalysisCommands(
    const BuildAction& action, const AnalyzerConfig& config,
    const StatisticsData& statistics) {
  const std::optional<std::vector<std::string>> command =
      StatisticsCollectCommand(action, config, action.source);
  if (!command) return {};
  const std::string output = util::pypath::Join(
      {statistics.stat_tmp_dir,
       util::pypath::Basename(action.source) + util::Uuid4() + ".stat"});
  return {"mkdir -p " + statistics.stat_tmp_dir,
          util::Join(*command, " ") + " > " + output + " 2>&1"};
}

