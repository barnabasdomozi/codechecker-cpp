// docs/usage/makefile-mode.md

import { readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { describe, expect } from '@jest/globals';
import { cc, run } from '../src/run';
import { useSandbox } from '../src/sandbox';
import { useCase } from '../src/usecase';
import { logMessages } from '../src/normalize';
import { DOC_ANALYZERS, loggedProject } from '../src/projects';
import { plainReports } from '../src/reports';

const box = useSandbox();

async function makefileProject(): Promise<string> {
  const root = await loggedProject(box, 'demo');
  const result = await cc(['analyze', 'compile_commands.json', '-o', 'reports', ...DOC_ANALYZERS, '--makefile'], { cwd: root });
  expect(result).toExitWith(0);
  expect(logMessages(result.output, 'INFO')).toContain('Done.');
  return root;
}

const plists = (dir: string) => readdirSync(dir).filter((f) => f.endsWith('.plist'));

describe('usage/makefile-mode.md', () => {
  useCase('makefile-mode.md', 'Create the Makefile', async () => {
    const root = await makefileProject();
    const files = readdirSync(path.join(root, 'reports'));
    for (const f of ['Makefile', 'metadata.json', 'compile_cmd.json', 'compiler_info.json', 'unique_compile_commands.json', 'conf', 'fixit']) {
      expect(files).toContain(f);
    }
    expect(plists(path.join(root, 'reports'))).toEqual([]);
    const makefile = readFileSync(path.join(root, 'reports', 'Makefile'), 'utf8');
    expect(makefile).toMatch(/^#\n# Autogenerated by CodeChecker v\S+\.\n#\n# DO NOT EDIT UNLESS YOU ARE SURE THAT YOU KNOW WHAT YOU ARE DOING\.\n#\n/);
    expect(makefile).toContain('# Default target to run all analysis.\ndefault: all');
    expect(makefile).toContain("# Target to run only 'clangsa' analysis.\nall: all_clangsa");
    expect(makefile).toContain("# Target to run only 'clangtidy' analysis.\nall: all_clangtidy");
    expect(makefile).toContain("# Target to run only 'cppcheck' analysis.\nall: all_cppcheck");
  });

  useCase('makefile-mode.md', 'Run it', async () => {
    const root = await makefileProject();
    const made = await run('make', ['-f', 'reports/Makefile', '-j2'], { cwd: root });
    expect(made).toExitWith(0);
    expect(plists(path.join(root, 'reports')).length).toBeGreaterThan(0);
    const parsed = await cc(['parse', 'reports'], { cwd: root });
    expect(parsed).toExitWith(2);
    // Cppcheck's raw plist files are read too, with checker names without
    // the cppcheck- prefix (known issue #13).
    expect(plainReports(parsed.stdout).map((r) => `${path.basename(r.path)}:${r.line}:${r.column} ${r.checker}`).sort()).toEqual(
      [
        'main.c:11:12 core.DivideZero',
        'main.c:11:12 zerodiv',
        'main.c:21:7 clang-diagnostic-unused-variable',
        'main.c:25:10 clang-diagnostic-uninitialized',
        'main.c:25:10 uninitvar',
        'style.cpp:11:12 zerodiv',
      ].sort(),
    );
  });

  useCase('makefile-mode.md', 'Run it', async () => {
    const root = await makefileProject();
    expect(await run('make', ['-f', 'reports/Makefile', 'all_clangsa'], { cwd: root })).toExitWith(0);
    expect(plists(path.join(root, 'reports')).every((f) => f.includes('_clangsa_'))).toBe(true);
    expect(plists(path.join(root, 'reports'))).toHaveLength(3);
  }, { name: 'one analyzer target' });

  useCase('makefile-mode.md', 'Run it', async () => {
    const root = await makefileProject();
    expect(await run('make', ['-f', 'reports/Makefile', '-i'], { cwd: root })).toExitWith(0);
    const status = await cc(['parse', 'reports', '--status', '-e', 'json'], { cwd: root });
    const json = JSON.parse(status.stdout) as { analyzers: Record<string, { summary: Record<string, number> }> };
    expect(json.analyzers.clangsa.summary['up-to-date']).toBe(3);
    // The clang-tidy result files have other names than analyze writes, so
    // --status thinks they are missing.
    expect(json.analyzers['clang-tidy'].summary).toMatchObject({ 'up-to-date': 0, missing: 3 });
    expect(json.analyzers.cppcheck.summary).toMatchObject({ 'up-to-date': 0, missing: 3 });
    const parsed = await cc(['parse', 'reports'], { cwd: root });
    expect(plainReports(parsed.stdout).some((r) => r.checker.startsWith('clang-diagnostic-'))).toBe(true);
  }, { name: 'parse --status misses the clang-tidy results', knownIssue: 13 });
});
